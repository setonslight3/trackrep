                    Text(
                        text = "Track modifies plans only through approved, validated application functions:\n" +
                                "• Replace exercises with suitable alternatives\n" +
                                "• Adjust sets, reps, and rest intervals\n" +
                                "• Reschedule missed sessions safely\n" +
